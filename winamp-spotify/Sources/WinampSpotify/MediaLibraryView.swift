import AppKit
import SkinKit
import PlayerCore

protocol MediaLibraryViewDelegate: AnyObject {
    /// Play one track now.
    func mediaLibraryView(_ view: MediaLibraryView, didActivate entry: PlaylistEntry, contextURI: String?)
    /// Append the current view's tracks to the playlist.
    func mediaLibraryView(_ view: MediaLibraryView, didEnqueue entries: [PlaylistEntry])
    /// Replace the playlist with the current view's tracks.
    func mediaLibraryView(_ view: MediaLibraryView, didReplacePlaylistWith entries: [PlaylistEntry], name: String)
    func mediaLibraryViewDidRequestClose(_ view: MediaLibraryView)
}

/// The media library: search, artists, albums, playlists and liked songs, drawn
/// entirely in the current skin's colours.
///
/// Nothing here is blitted from a downloaded skin, because no skin has artwork
/// for a tab strip or a search field. Instead the window is framed in the
/// skin's own `pledit.bmp` tiles, and every control inside is generated by
/// `ThemedChrome` from the palette `SkinThemeDerivation` pulled out of that same
/// skin. Swap skins and this window changes with the rest of the app.
final class MediaLibraryView: NSView {

    weak var delegate: MediaLibraryViewDelegate?

    private let renderer: SkinRenderer
    private let browser: MediaBrowser
    private let windowFrame: SkinnedFrame
    private let chrome: ThemedChromeCache
    private var text: ThemedText

    /// One real text field, for one good reason: implementing text input by
    /// hand means no IME, no selection, no paste, no undo. Everything around it
    /// is drawn; this is styled to match.
    private let searchField = NSTextField()

    // MARK: Geometry, in layout pixels

    private let tabHeight = 14
    private let navHeight = 16
    private let headerHeight = 46
    private let rowHeight = 18
    private let thumbnailSize = 14
    private let buttonHeight = 14

    private var scrollRow = 0
    private var isDraggingScrollbar = false
    private var hoveredTab: MediaBrowser.Section?
    private var pressedButton: BottomButton?

    private enum BottomButton: Hashable {
        case play
        case enqueue
        case replace
    }

    init(renderer: SkinRenderer, browser: MediaBrowser) {
        self.renderer = renderer
        self.browser = browser
        let cache = ThemedChromeCache(theme: renderer.skin.effectiveTheme)
        self.chrome = cache
        self.windowFrame = SkinnedFrame(renderer: renderer, chrome: cache)
        self.text = ThemedText(renderer: renderer, theme: renderer.skin.effectiveTheme)
        super.init(frame: NSRect(x: 0, y: 0, width: 420, height: 320))
        wantsLayer = true
        layer?.magnificationFilter = .nearest
        configureSearchField()
        addTrackingArea()
    }

    required init?(coder: NSCoder) {
        fatalError("MediaLibraryView is created in code only")
    }

    override var isFlipped: Bool { false }
    override var acceptsFirstResponder: Bool { true }

    /// Re-reads the theme after a skin change and drops the generated art.
    func skinDidChange() {
        let theme = renderer.skin.effectiveTheme
        chrome.apply(theme: theme)
        text = ThemedText(renderer: renderer, theme: theme)
        styleSearchField(theme: theme)
        needsDisplay = true
    }

    func modelDidChange() {
        // A new result set invalidates the scroll position; clamp rather than
        // reset, so refreshing the same view keeps your place.
        scrollRow = min(scrollRow, maximumScrollRow)
        updateSearchFieldVisibility()
        needsDisplay = true
    }

    // MARK: - Search field

    private func configureSearchField() {
        searchField.isBordered = false
        searchField.drawsBackground = false
        searchField.focusRingType = .none
        searchField.isBezeled = false
        searchField.usesSingleLineMode = true
        searchField.lineBreakMode = .byTruncatingTail
        searchField.placeholderString = "Search Spotify"
        searchField.target = self
        searchField.action = #selector(searchFieldSubmitted)
        searchField.delegate = self
        styleSearchField(theme: chrome.theme)
        addSubview(searchField)
        updateSearchFieldVisibility()
    }

    private func styleSearchField(theme: SkinTheme) {
        searchField.textColor = renderer.nsColor(theme.displayText)
        searchField.font = .systemFont(ofSize: 11 * CGFloat(renderer.scale))
        // The insertion point has to be visible against the skin's well, which
        // may be almost any colour.
        if let fieldEditor = window?.fieldEditor(false, for: searchField) as? NSTextView {
            fieldEditor.insertionPointColor = renderer.nsColor(theme.displayText)
        }
    }

    private func updateSearchFieldVisibility() {
        // deviceRect below flips through the renderer's canvas height, and this
        // can run before the first draw() has set it.
        renderer.canvasHeight = layoutSize.height
        let isSearch = browser.section == .search && !browser.canGoBack
        searchField.isHidden = !isSearch
        guard isSearch else { return }
        let rect = searchFieldRect()
        // Inset by the well's bevel so the text does not touch the edge.
        searchField.frame = renderer.deviceRect(
            PixelRect(x: rect.x + 3, y: rect.y + 3, width: rect.width - 6, height: rect.height - 5)
        )
    }

    @objc private func searchFieldSubmitted() {
        browser.submitSearch()
    }

    // MARK: - Layout maths

    private var layoutSize: (width: Int, height: Int) {
        (Int(bounds.width) / renderer.scale, Int(bounds.height) / renderer.scale)
    }

    private var contentRect: PixelRect {
        let size = layoutSize
        return windowFrame.contentRect(width: size.width, height: size.height)
    }

    private var tabStripRect: PixelRect {
        let content = contentRect
        return PixelRect(x: content.x, y: content.y, width: content.width, height: tabHeight)
    }

    private var navBarRect: PixelRect {
        let content = contentRect
        return PixelRect(x: content.x, y: content.y + tabHeight, width: content.width, height: navHeight)
    }

    private func searchFieldRect() -> PixelRect {
        let nav = navBarRect
        let backWidth = browser.canGoBack ? 34 : 0
        return PixelRect(
            x: nav.x + backWidth,
            y: nav.y + 1,
            width: max(20, nav.width - backWidth - 44),
            height: nav.height - 2
        )
    }

    private var backButtonRect: PixelRect {
        let nav = navBarRect
        return PixelRect(x: nav.x, y: nav.y + 1, width: 32, height: nav.height - 2)
    }

    private var searchButtonRect: PixelRect {
        let nav = navBarRect
        return PixelRect(x: nav.maxX - 42, y: nav.y + 1, width: 42, height: nav.height - 2)
    }

    private var hasHeader: Bool {
        browser.headerArtworkURL != nil || browser.headerSubtitle != nil
    }

    private var headerRect: PixelRect {
        let content = contentRect
        return PixelRect(
            x: content.x,
            y: content.y + tabHeight + navHeight,
            width: content.width,
            height: hasHeader ? headerHeight : 0
        )
    }

    private var listRect: PixelRect {
        let content = contentRect
        let top = content.y + tabHeight + navHeight + (hasHeader ? headerHeight : 0)
        return PixelRect(
            x: content.x,
            y: top,
            width: content.width,
            height: max(0, content.maxY - top)
        )
    }

    private var visibleRowCount: Int {
        max(1, listRect.height / rowHeight)
    }

    private var maximumScrollRow: Int {
        max(0, browser.rows.count - visibleRowCount)
    }

    private func tabRect(_ index: Int) -> PixelRect {
        let strip = tabStripRect
        let count = MediaBrowser.Section.allCases.count
        let width = strip.width / count
        let x = strip.x + index * width
        // The last tab absorbs the rounding remainder so the strip is flush.
        let isLast = index == count - 1
        return PixelRect(
            x: x,
            y: strip.y,
            width: isLast ? strip.maxX - x : width,
            height: strip.height
        )
    }

    private func bottomButtonRect(_ button: BottomButton) -> PixelRect {
        let size = layoutSize
        let y = size.height - SkinnedFrame.bottomHeight + 5
        let widths: [(BottomButton, Int)] = [(.play, 38), (.enqueue, 50), (.replace, 50)]
        var x = 8
        for (candidate, width) in widths {
            if candidate == button {
                return PixelRect(x: x, y: y, width: width, height: buttonHeight)
            }
            x += width + 4
        }
        return .zero
    }

    // MARK: - Drawing

    override func draw(_ dirtyRect: NSRect) {
        guard let context = NSGraphicsContext.current?.cgContext else { return }
        context.configureForPixelArt()

        let size = layoutSize
        renderer.canvasHeight = size.height
        let isActive = window?.isKeyWindow ?? false

        windowFrame.draw(
            in: context,
            width: size.width,
            height: size.height,
            isActive: isActive,
            title: .text("MEDIA LIBRARY", tint: chrome.theme.faceText)
        )

        drawTabs(in: context)
        drawNavBar(in: context)
        if hasHeader { drawHeader(in: context) }
        drawList(in: context)
        drawBottomBar(in: context, size: size)

        if browser.rows.count > visibleRowCount {
            let fraction = maximumScrollRow == 0 ? 0 : Double(scrollRow) / Double(maximumScrollRow)
            windowFrame.drawScrollbar(
                in: context,
                width: size.width,
                content: listRect,
                fraction: fraction,
                pressed: isDraggingScrollbar
            )
        }
    }

    private func drawTabs(in context: CGContext) {
        for (index, section) in MediaBrowser.Section.allCases.enumerated() {
            let rect = tabRect(index)
            let selected = section == browser.section
            if let image = chrome.tab(
                width: rect.width,
                height: rect.height,
                selected: selected,
                hovered: hoveredTab == section
            ) {
                renderer.draw(image, at: rect.x, y: rect.y, in: context)
            }
            // Tabs use the skin's own glyphs: they are short, uppercase labels,
            // which is exactly what the bitmap font is good at, and it is the
            // strongest signal that this window belongs to the skin.
            text.draw(
                section.title,
                in: rect,
                color: chrome.tabTextColor(selected: selected),
                face: .bitmap,
                alignment: .center,
                context: context
            )
        }
    }

    private func drawNavBar(in context: CGContext) {
        let nav = navBarRect
        if let panel = chrome.panel(width: nav.width, height: nav.height, bevelled: false) {
            renderer.draw(panel, at: nav.x, y: nav.y, in: context)
        }

        if browser.canGoBack {
            let rect = backButtonRect
            if let image = chrome.button(width: rect.width, height: rect.height, state: .normal) {
                renderer.draw(image, at: rect.x, y: rect.y, in: context)
            }
            text.draw(
                "< BACK",
                in: rect,
                color: chrome.buttonTextColor(.normal),
                face: .bitmap,
                alignment: .center,
                context: context
            )
        }

        if browser.section == .search && !browser.canGoBack {
            let well = searchFieldRect()
            if let image = chrome.well(width: well.width, height: well.height) {
                renderer.draw(image, at: well.x, y: well.y, in: context)
            }
            let button = searchButtonRect
            if let image = chrome.button(width: button.width, height: button.height, state: .normal) {
                renderer.draw(image, at: button.x, y: button.y, in: context)
            }
            text.draw(
                "FIND",
                in: button,
                color: chrome.buttonTextColor(.normal),
                face: .bitmap,
                alignment: .center,
                context: context
            )
        } else {
            // Breadcrumb: the last two levels, which is as much as fits and as
            // much as anyone needs to know where they are.
            let crumb = browser.breadcrumb.suffix(2).joined(separator: "  \u{203A}  ")
            let backWidth = browser.canGoBack ? 36 : 0
            text.draw(
                crumb,
                in: PixelRect(
                    x: nav.x + backWidth + 4,
                    y: nav.y,
                    width: max(0, nav.width - backWidth - 8),
                    height: nav.height
                ),
                color: chrome.theme.faceText,
                face: .emphasis,
                context: context
            )
        }
    }

    private func drawHeader(in context: CGContext) {
        let header = headerRect
        if let panel = chrome.panel(width: header.width, height: header.height, bevelled: false) {
            renderer.draw(panel, at: header.x, y: header.y, in: context)
        }

        let artSize = header.height - 8
        let artRect = PixelRect(x: header.x + 4, y: header.y + 4, width: artSize, height: artSize)

        let artwork = ArtworkLoader.shared.image(for: browser.headerArtworkURL) { [weak self] in
            self?.needsDisplay = true
        }
        if let artwork {
            context.saveGState()
            context.clip(to: renderer.deviceRect(
                PixelRect(x: artRect.x + 1, y: artRect.y + 1, width: artSize - 2, height: artSize - 2)
            ))
            context.draw(artwork, in: renderer.deviceRect(artRect))
            context.restoreGState()
        }
        if let border = chrome.artworkFrame(size: artSize, hasImage: artwork != nil) {
            // The frame is drawn over the image: it is a bevel with a
            // transparent middle when an image is present.
            renderer.draw(border, at: artRect.x, y: artRect.y, in: context)
        }

        let textX = artRect.maxX + 6
        let textWidth = max(0, header.maxX - textX - 4)
        // Faceplate colours, not display colours: the header strip is a panel,
        // and a well-legible colour on the dark well can vanish here.
        text.draw(
            browser.location.title,
            in: PixelRect(x: textX, y: header.y + 8, width: textWidth, height: 14),
            color: chrome.theme.faceText,
            face: .emphasis,
            context: context
        )
        if let subtitle = browser.headerSubtitle {
            text.draw(
                subtitle,
                in: PixelRect(x: textX, y: header.y + 23, width: textWidth, height: 13),
                color: chrome.theme.faceTextDim,
                face: .body,
                context: context
            )
        }
    }

    private func drawList(in context: CGContext) {
        let list = listRect
        guard list.width > 0, list.height > 0 else { return }

        if let well = chrome.well(
            width: list.width,
            height: list.height,
            interior: chrome.theme.listBackground
        ) {
            renderer.draw(well, at: list.x, y: list.y, in: context)
        }

        guard !browser.rows.isEmpty else {
            let message: String
            if browser.isLoading {
                message = "LOADING\u{2026}"
            } else if let error = browser.errorMessage {
                message = error
            } else if browser.section == .search {
                message = "TYPE TO SEARCH SPOTIFY"
            } else {
                message = "NOTHING HERE"
            }
            text.draw(
                message,
                in: PixelRect(x: list.x + 4, y: list.y + 8, width: list.width - 8, height: 14),
                color: chrome.theme.displayDim,
                face: .body,
                alignment: .center,
                context: context
            )
            return
        }

        // Column layout: thumbnail, title, subtitle, trailing, chevron.
        let interior = PixelRect(
            x: list.x + 2, y: list.y + 2,
            width: list.width - 4, height: list.height - 4
        )
        let trailingWidth = 46
        let chevronWidth = 8
        let available = max(20, interior.width - thumbnailSize - 6 - trailingWidth - chevronWidth - 6)
        let titleWidth = Int(Double(available) * 0.58)
        let subtitleWidth = available - titleWidth

        for offset in 0 ..< visibleRowCount {
            let index = scrollRow + offset
            guard browser.rows.indices.contains(index) else { break }
            let row = browser.rows[index]
            let y = interior.y + offset * rowHeight
            guard y + rowHeight <= interior.maxY else { break }

            let rowRect = PixelRect(x: interior.x, y: y, width: interior.width, height: rowHeight)
            let isSelected = row.id == browser.selectedRowID

            if isSelected {
                context.setFillColor(renderer.cgColor(chrome.theme.selectionBackground))
                context.fill(renderer.deviceRect(rowRect))
            } else if index % 2 == 1 {
                context.setFillColor(renderer.cgColor(chrome.theme.listAlternate))
                context.fill(renderer.deviceRect(rowRect))
            }

            let titleColor = isSelected ? chrome.theme.selectionText : chrome.theme.listText
            let dimColor = isSelected
                ? chrome.theme.selectionText.mixed(with: chrome.theme.selectionBackground, amount: 0.35)
                : chrome.theme.listText.mixed(with: chrome.theme.listBackground, amount: 0.45)

            var x = rowRect.x + 2

            // Thumbnail, or a framed placeholder so rows do not jump when
            // artwork arrives.
            if row.kind != .navigation {
                let thumbRect = PixelRect(
                    x: x,
                    y: y + (rowHeight - thumbnailSize) / 2,
                    width: thumbnailSize,
                    height: thumbnailSize
                )
                let thumb = ArtworkLoader.shared.image(for: row.artworkURL) { [weak self] in
                    self?.needsDisplay = true
                }
                if let thumb {
                    context.saveGState()
                    context.clip(to: renderer.deviceRect(thumbRect))
                    context.draw(thumb, in: renderer.deviceRect(thumbRect))
                    context.restoreGState()
                } else if let placeholder = chrome.artworkFrame(size: thumbnailSize, hasImage: false) {
                    renderer.draw(placeholder, at: thumbRect.x, y: thumbRect.y, in: context)
                }
            }
            x += thumbnailSize + 4

            text.draw(
                row.title,
                in: PixelRect(x: x, y: y, width: titleWidth, height: rowHeight),
                color: titleColor,
                face: row.kind == .navigation ? .emphasis : .body,
                context: context
            )
            x += titleWidth + 4

            if let subtitle = row.subtitle {
                text.draw(
                    subtitle,
                    in: PixelRect(x: x, y: y, width: subtitleWidth, height: rowHeight),
                    color: dimColor,
                    face: .body,
                    context: context
                )
            }
            x += subtitleWidth + 4

            if let trailing = row.trailing {
                text.draw(
                    trailing,
                    in: PixelRect(x: x, y: y, width: trailingWidth, height: rowHeight),
                    color: dimColor,
                    face: .numeric,
                    alignment: .right,
                    context: context
                )
            }

            // Drill-in affordance, in the skin's glyphs.
            if row.destination != nil {
                text.draw(
                    ">",
                    in: PixelRect(
                        x: rowRect.maxX - chevronWidth,
                        y: y,
                        width: chevronWidth,
                        height: rowHeight
                    ),
                    color: dimColor,
                    face: .bitmap,
                    alignment: .right,
                    context: context
                )
            }
        }
    }

    private func drawBottomBar(in context: CGContext, size: (width: Int, height: Int)) {
        let buttons: [(BottomButton, String)] = [
            (.play, "PLAY"),
            (.enqueue, "ENQUEUE"),
            (.replace, "REPLACE"),
        ]
        let hasTracks = !browser.allEntries.isEmpty

        for (button, label) in buttons {
            let rect = bottomButtonRect(button)
            let state: ThemedChrome.ControlState = !hasTracks
                ? .disabled
                : (pressedButton == button ? .pressed : .normal)
            if let image = chrome.button(width: rect.width, height: rect.height, state: state) {
                renderer.draw(image, at: rect.x, y: rect.y, in: context)
            }
            text.draw(
                label,
                in: rect,
                color: chrome.buttonTextColor(state),
                face: .bitmap,
                alignment: .center,
                context: context
            )
        }

        // Status line, in a recessed strip. Drawing it straight onto the
        // skin's bottom-panel artwork means an unknown background; a well makes
        // the contrast guaranteed, and a sunken readout is the more Winamp
        // thing anyway.
        let statusRect = PixelRect(
            x: 8,
            y: size.height - SkinnedFrame.bottomHeight + 21,
            width: max(0, size.width - 16),
            height: 12
        )
        if let well = chrome.well(width: statusRect.width, height: statusRect.height) {
            renderer.draw(well, at: statusRect.x, y: statusRect.y, in: context)
        }
        let status: String
        if browser.isLoading {
            status = "Loading\u{2026}"
        } else if let error = browser.errorMessage {
            status = error
        } else {
            let entries = browser.allEntries
            if entries.isEmpty {
                status = browser.rows.isEmpty ? "" : "\(browser.rows.count) items"
            } else {
                let total = entries.reduce(0) { $0 + $1.duration }
                status = "\(entries.count) tracks \u{00B7} \(PlaylistEntry.formatDuration(total))"
            }
        }
        text.draw(
            status,
            in: PixelRect(
                x: statusRect.x + 3, y: statusRect.y,
                width: statusRect.width - 6, height: statusRect.height
            ),
            color: browser.errorMessage == nil
                ? chrome.theme.displayDim
                : SkinColor.legible(chrome.theme.accent, on: chrome.theme.displayBackground),
            face: .body,
            context: context
        )
    }

    // MARK: - Hit testing

    private func row(at point: NSPoint) -> MediaBrowser.Row? {
        let (_, y) = renderer.layoutPoint(from: point)
        let interior = PixelRect(
            x: listRect.x + 2, y: listRect.y + 2,
            width: listRect.width - 4, height: listRect.height - 4
        )
        guard y >= interior.y, y < interior.maxY else { return nil }
        let index = scrollRow + (y - interior.y) / rowHeight
        return browser.rows.indices.contains(index) ? browser.rows[index] : nil
    }

    override func mouseDown(with event: NSEvent) {
        let point = convert(event.locationInWindow, from: nil)
        let (x, y) = renderer.layoutPoint(from: point)
        let size = layoutSize

        // Title bar.
        if y < SkinnedFrame.topHeight {
            if windowFrame.closeButtonRect(width: size.width).contains(x: x, y: y) {
                delegate?.mediaLibraryViewDidRequestClose(self)
                return
            }
            window?.performDrag(with: event)
            return
        }

        // Tabs.
        for (index, section) in MediaBrowser.Section.allCases.enumerated()
        where tabRect(index).contains(x: x, y: y) {
            browser.select(section: section)
            scrollRow = 0
            return
        }

        // Nav bar.
        if navBarRect.contains(x: x, y: y) {
            if browser.canGoBack, backButtonRect.contains(x: x, y: y) {
                browser.goBack()
                scrollRow = 0
                return
            }
            if browser.section == .search, !browser.canGoBack {
                if searchButtonRect.contains(x: x, y: y) {
                    browser.submitSearch()
                    return
                }
                if searchFieldRect().contains(x: x, y: y) {
                    window?.makeFirstResponder(searchField)
                    return
                }
            }
            return
        }

        // Bottom buttons.
        for button in [BottomButton.play, .enqueue, .replace]
        where bottomButtonRect(button).contains(x: x, y: y) {
            pressedButton = button
            needsDisplay = true
            return
        }

        if y >= size.height - SkinnedFrame.bottomHeight {
            window?.performDrag(with: event)
            return
        }

        // Scrollbar.
        if x >= size.width - SkinnedFrame.rightWidth, browser.rows.count > visibleRowCount {
            isDraggingScrollbar = true
            updateScroll(forPointAtY: y)
            return
        }

        // List.
        if let row = row(at: point) {
            browser.selectedRowID = row.id
            if event.clickCount >= 2 { activate(row) }
            needsDisplay = true
            return
        }

        window?.performDrag(with: event)
    }

    override func mouseDragged(with event: NSEvent) {
        guard isDraggingScrollbar else { return }
        let point = convert(event.locationInWindow, from: nil)
        let (_, y) = renderer.layoutPoint(from: point)
        updateScroll(forPointAtY: y)
    }

    override func mouseUp(with event: NSEvent) {
        if isDraggingScrollbar {
            isDraggingScrollbar = false
            needsDisplay = true
        }
        if let button = pressedButton {
            let point = convert(event.locationInWindow, from: nil)
            let (x, y) = renderer.layoutPoint(from: point)
            // Only fire if the mouse is still on the button.
            if bottomButtonRect(button).contains(x: x, y: y) { perform(button) }
            pressedButton = nil
            needsDisplay = true
        }
    }

    override func mouseMoved(with event: NSEvent) {
        let point = convert(event.locationInWindow, from: nil)
        let (x, y) = renderer.layoutPoint(from: point)
        var hovered: MediaBrowser.Section?
        for (index, section) in MediaBrowser.Section.allCases.enumerated()
        where tabRect(index).contains(x: x, y: y) {
            hovered = section
        }
        if hovered != hoveredTab {
            hoveredTab = hovered
            needsDisplay = true
        }
    }

    override func mouseExited(with event: NSEvent) {
        if hoveredTab != nil {
            hoveredTab = nil
            needsDisplay = true
        }
    }

    override func scrollWheel(with event: NSEvent) {
        guard browser.rows.count > visibleRowCount else { return }
        let lines = event.hasPreciseScrollingDeltas
            ? Int((event.scrollingDeltaY / 10).rounded())
            : Int(event.scrollingDeltaY.rounded())
        guard lines != 0 else { return }
        scrollRow = min(maximumScrollRow, max(0, scrollRow - lines))
        needsDisplay = true
    }

    override func keyDown(with event: NSEvent) {
        switch event.keyCode {
        case 125: moveSelection(by: 1)       // Down
        case 126: moveSelection(by: -1)      // Up
        case 121: moveSelection(by: visibleRowCount)   // Page down
        case 116: moveSelection(by: -visibleRowCount)  // Page up
        case 36, 76:                          // Return
            if let id = browser.selectedRowID,
               let row = browser.rows.first(where: { $0.id == id }) {
                activate(row)
            }
        case 53:                              // Escape
            if browser.canGoBack {
                browser.goBack()
                scrollRow = 0
            } else {
                delegate?.mediaLibraryViewDidRequestClose(self)
            }
        default:
            super.keyDown(with: event)
        }
    }

    // MARK: - Actions

    private func activate(_ row: MediaBrowser.Row) {
        if let entry = browser.activate(row) {
            delegate?.mediaLibraryView(self, didActivate: entry, contextURI: browser.contextURI)
        } else {
            scrollRow = 0
        }
        needsDisplay = true
    }

    private func perform(_ button: BottomButton) {
        let entries = browser.allEntries
        guard !entries.isEmpty else { return }
        switch button {
        case .play:
            // Play the selection if there is one, otherwise start at the top.
            let selected = browser.selectedRowID
                .flatMap { id in browser.rows.first { $0.id == id } }?
                .entry
            delegate?.mediaLibraryView(
                self,
                didActivate: selected ?? entries[0],
                contextURI: browser.contextURI
            )
        case .enqueue:
            delegate?.mediaLibraryView(self, didEnqueue: entries)
        case .replace:
            delegate?.mediaLibraryView(
                self,
                didReplacePlaylistWith: entries,
                name: browser.location.title
            )
        }
    }

    private func moveSelection(by delta: Int) {
        guard !browser.rows.isEmpty else { return }
        let current = browser.selectedRowID
            .flatMap { id in browser.rows.firstIndex { $0.id == id } } ?? -1
        let next = min(browser.rows.count - 1, max(0, current + delta))
        browser.selectedRowID = browser.rows[next].id
        if next < scrollRow { scrollRow = next }
        if next >= scrollRow + visibleRowCount { scrollRow = next - visibleRowCount + 1 }
        needsDisplay = true
    }

    private func updateScroll(forPointAtY y: Int) {
        let list = listRect
        let thumbHeight = renderer.image(.playlistScrollThumb)?.height ?? 18
        let travel = max(1, list.height - thumbHeight)
        let offset = y - list.y - thumbHeight / 2
        let fraction = min(1, max(0, Double(offset) / Double(travel)))
        scrollRow = Int((fraction * Double(maximumScrollRow)).rounded())
        needsDisplay = true
    }

    // MARK: - Tracking

    private func addTrackingArea() {
        let area = NSTrackingArea(
            rect: .zero,
            options: [.mouseMoved, .mouseEnteredAndExited, .activeInKeyWindow, .inVisibleRect],
            owner: self,
            userInfo: nil
        )
        addTrackingArea(area)
    }

    override func layout() {
        super.layout()
        updateSearchFieldVisibility()
    }
}

// MARK: - Search field wiring

extension MediaLibraryView: NSTextFieldDelegate {
    func controlTextDidChange(_ notification: Notification) {
        // Debounced inside the browser, so typing does not fire a request per
        // keystroke.
        browser.searchTextChanged(searchField.stringValue)
    }
}
